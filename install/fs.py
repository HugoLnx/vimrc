"""Filesystem helpers shared by the enforcer (moved from symlink.py).

link_or_copy / sync_gitconfig / sync_local_nvim_config return True when a
change was made (or would be made in dry-run), False when already up to date.
"""

import datetime
import filecmp
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
# Overridable (tests monkeypatch this so the real repo file is untouched).
LOCAL_NVIM_TARGET = REPO_ROOT / 'nvim' / 'lua' / 'user' / 'local.lua'


def load_config(config_path):
    try:
        import yaml
    except ImportError:
        print(
            "error: PyYAML is required to read config.yml.\n"
            "Install it with: pip install pyyaml",
            file=sys.stderr,
        )
        sys.exit(1)

    with open(config_path) as f:
        return yaml.safe_load(f) or {}


def backup_if_exists(target):
    if target.exists() or target.is_symlink():
        timestamp = datetime.datetime.now().strftime('%Y%m%d%H%M%S')
        backup_path = target.parent / f"{target.name}_{timestamp}.bkp"
        print(f"  backing up {target} -> {backup_path}")
        target.rename(backup_path)


def already_linked(source, target):
    if not target.is_symlink():
        return False
    try:
        return target.resolve() == source.resolve()
    except FileNotFoundError:
        return False


def copy_path(source, target):
    target.parent.mkdir(parents=True, exist_ok=True)
    if source.is_dir():
        shutil.copytree(source, target)
    else:
        shutil.copy2(source, target)


def dirs_equal(source, target):
    cmp = filecmp.dircmp(source, target)
    if cmp.left_only or cmp.right_only or cmp.diff_files or cmp.funny_files:
        return False
    _, mismatch, errors = filecmp.cmpfiles(source, target, cmp.common_files, shallow=False)
    if mismatch or errors:
        return False
    return all(dirs_equal(source / d, target / d) for d in cmp.common_dirs)


def already_copied(source, target):
    if source.is_dir() and target.is_dir():
        return dirs_equal(source, target)
    if not target.is_file() or not source.is_file():
        return False
    return filecmp.cmp(source, target, shallow=False)


def link_or_copy(source, target, copy, dry_run):
    if copy:
        if already_copied(source, target):
            print(f"  up to date: {target}")
            return False

        action = f"copy {source} -> {target}"
        if dry_run:
            print(f"  [dry-run] {action}")
            return True
        print(f"  {action}")
        backup_if_exists(target)
        copy_path(source, target)
        return True

    if already_linked(source, target):
        print(f"  up to date: {target}")
        return False

    action = f"symlink {source} -> {target}"
    if dry_run:
        print(f"  [dry-run] {action}")
        return True

    print(f"  {action}")
    backup_if_exists(target)
    target.parent.mkdir(parents=True, exist_ok=True)
    try:
        target.symlink_to(source, target_is_directory=source.is_dir())
    except OSError as e:
        print(
            f"  warning: could not create symlink ({e}); falling back to copy.\n"
            f"           re-run this script after 'git pull' to pick up changes.",
            file=sys.stderr,
        )
        copy_path(source, target)
    return True


def gitconfig_content(unity_yaml_merge):
    content = (REPO_ROOT / 'gitconfig').read_text()
    if unity_yaml_merge:
        # gitconfig value syntax treats backslash as an escape character, so
        # a raw Windows path (single backslashes) must have them doubled or
        # git rejects the file with "bad config line".
        escaped_path = unity_yaml_merge.replace('\\', '\\\\')
        content += (
            '\n[mergetool "unityyamlmerge"]\n'
            '\ttrustExitCode = false\n'
            f'\tcmd = \'{escaped_path}\' merge -p "$BASE" "$REMOTE" "$LOCAL" "$MERGED"\n'
        )
    return content


def sync_gitconfig(target, unity_yaml_merge, dry_run):
    content = gitconfig_content(unity_yaml_merge)
    if target.is_file() and target.read_text() == content:
        print(f"  up to date: {target}")
        return False

    action = f"write {target}"
    if dry_run:
        print(f"  [dry-run] {action}")
        return True

    print(f"  {action}")
    backup_if_exists(target)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content)
    return True


def local_nvim_config_content(csharp_lsp):
    value = 'true' if csharp_lsp else 'false'
    return (
        "-- Generated by install/enforce.py from config.yml's `csharp_lsp`\n"
        "-- option. Do not edit directly; edit config.yml and re-run the\n"
        "-- script.\n"
        "return {\n"
        f"  csharp_lsp = {value},\n"
        "}\n"
    )


def sync_local_nvim_config(csharp_lsp, dry_run):
    target = LOCAL_NVIM_TARGET
    content = local_nvim_config_content(csharp_lsp)
    if target.is_file() and target.read_text() == content:
        print(f"  up to date: {target}")
        return False

    action = f"write {target}"
    if dry_run:
        print(f"  [dry-run] {action}")
        return True
    print(f"  {action}")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content)
    return True
